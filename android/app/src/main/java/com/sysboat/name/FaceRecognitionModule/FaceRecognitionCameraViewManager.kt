package com.sysboat.name.FaceRecognitionModule

import android.util.Log
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReadableArray
import com.facebook.react.modules.core.DeviceEventManagerModule
import com.facebook.react.uimanager.SimpleViewManager
import com.facebook.react.uimanager.ThemedReactContext
import com.facebook.react.uimanager.annotations.ReactProp

class FaceRecognitionCameraViewManager(
    private val reactAppContext: ReactApplicationContext
) : SimpleViewManager<FaceRecognitionCameraView>() {

    companion object {
        private const val TAG = "FaceCameraViewManager"
        private const val COMMAND_START_CAMERA = 1
        private const val COMMAND_STOP_CAMERA = 2
        private const val COMMAND_SWITCH_CAMERA = 3
    }

    override fun getName() = "FaceRecognitionCameraView"

    override fun createViewInstance(reactContext: ThemedReactContext): FaceRecognitionCameraView {
        val view = FaceRecognitionCameraView(reactContext)

        // 1. Listener for Face Detection bounding boxes
        view.setFaceDetectedListener { faces ->
            val event = Arguments.createMap().apply {
                putInt("faceCount", faces.size)
            }
            reactAppContext
                .getJSModule(DeviceEventManagerModule.RCTDeviceEventEmitter::class.java)
                .emit("onFacesDetected", event)
        }

        // ⭐️ 2. Listener for Face Recognition results
        view.setRecognitionListener { result ->
            // 'result' is the WritableMap generated by recognizeImage in the View class
            reactAppContext
                .getJSModule(DeviceEventManagerModule.RCTDeviceEventEmitter::class.java)
                .emit("onFaceRecognized", result)
        }

        return view
    }

    @ReactProp(name = "cameraType")
    fun setCameraType(view: FaceRecognitionCameraView, type: String) {
        Log.d(TAG, "Camera type: $type")
    }

    override fun getCommandsMap(): Map<String, Int> = mapOf(
        "startCamera" to COMMAND_START_CAMERA,
        "stopCamera" to COMMAND_STOP_CAMERA,
        "switchCamera" to COMMAND_SWITCH_CAMERA
    )

    override fun receiveCommand(view: FaceRecognitionCameraView, commandId: Int, args: ReadableArray?) {
        when (commandId) {
            COMMAND_START_CAMERA -> view.startCamera()
            COMMAND_STOP_CAMERA -> view.stopCamera()
            COMMAND_SWITCH_CAMERA -> view.switchCamera()
            else -> Log.w(TAG, "Unknown command: $commandId")
        }
    }

    override fun onDropViewInstance(view: FaceRecognitionCameraView) {
        view.cleanup()
        super.onDropViewInstance(view)
    }
}